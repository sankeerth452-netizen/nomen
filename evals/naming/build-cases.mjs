// Turn crawled Sportsgirl products into Nomen test cases: what a buyer would type for each piece.
//   node evals/naming/build-cases.mjs <products.json from crawl.py>
// Writes evals/naming/cases.json (the runner reads it) and cases.md (for review). Both hold Sportsgirl's own
// product copy, so they are git-ignored: re-create them with crawl.py + this script.
import { readFileSync, writeFileSync } from "node:fs";

// Sportsgirl names start with a style name ("FELICITY Scalloped Denim Mini Dress"). Whether Nomen keeps style names
// is an open brand decision, so they are left out of the buyer's input. Reviewed by hand from the crawled names.
const STYLE_NAMES = new Set(["felicity", "annette", "clover", "stella", "catalina", "shelby", "bexley", "fiona", "annika", "anika", "harri",
  "freya", "zali", "caitlin", "zoe", "willow", "bryanna", "sadie", "the", "ella", "ayla", "mavis", "luna", "pippa", "alexis", "aiden", "hazel",
  "monique", "layla", "ruby", "evelyn", "rewind", "monty", "nora"]);
const GROUP = { dresses: "dresses", tops: "tops", shirts: "tops", tees: "tops", pants: "pants", jeans: "pants", skirts: "skirts", shorts: "shorts",
  knitwear: "knitwear", jackets: "jackets", bags: "bags", jewellery: "jewellery" };
const NOUN_FIX = { neckalce: "necklace" }; // a typo in one Sportsgirl name
const JOINED = { cornflowerblue: "cornflower blue", abstractprint: "abstract print", lightblue: "light blue" };
const PATTERNS = new Set(["check", "print", "floral", "stripe", "abstract print", "shadow floral"]);

const products = JSON.parse(readFileSync(process.argv[2], "utf8"));
const seen = new Set();
const cases = [];
for (const p of products) {
  if (!p.name || !p.description) continue;
  const key = p.product_code ?? p.slug;
  if (seen.has(key)) continue; // the same piece listed under two categories
  seen.add(key);

  const [base, suffix] = p.name.split(/\s+-\s+/);
  const words = base.toLowerCase().split(/\s+/);
  const style = STYLE_NAMES.has(words[0]) ? words[0] : null;
  const desc = style ? words.slice(1) : words;
  const noun = NOUN_FIX[desc.at(-1)] ?? desc.at(-1);
  const freeText = [...desc.slice(0, -1), noun].join(" ");

  // Colour: the name's " - COLOUR" suffix when there is one, else the web address after the product noun.
  let colour = suffix?.toLowerCase().replace(/\s*\/\s*/g, " and ") ?? null;
  if (!colour) {
    const slugWords = p.slug.replace(/-\d{6}-\d{3}$/, "").split("-");
    const at = slugWords.lastIndexOf(desc.at(-1));
    const rest = at >= 0 ? [...new Set(slugWords.slice(at + 1))].join(" ") : "";
    colour = rest ? (JOINED[rest] ?? rest) : null;
  }
  const isPattern = colour && PATTERNS.has(colour);

  // The description, with the style name taken out where it names this product ("The Clover Ruffle Shoulder...").
  let extra = p.description;
  if (style && desc[0]) extra = extra.replace(new RegExp(`\\b${style}\\s+(?=${desc[0]}\\b)`, "gi"), "");
  if (p.fabrication && /\d|pu|polyurethane|beads|plated/i.test(p.fabrication)) extra += ` Fabric: ${p.fabrication.toLowerCase()}.`;

  const input = { freeText, productType: noun, ...(isPattern ? { pattern: colour } : colour ? { colour } : {}), extra };
  cases.push({
    id: `${GROUP[p.category] ?? p.category}-${p.product_code ?? p.slug}`,
    tags: [GROUP[p.category] ?? p.category, "catalogue"],
    expect: "name",
    prompt: `${freeText} · ${noun}${colour ? ` · ${colour}` : ""}`,
    input,
    meta: { url: p.url, sportsgirl_name: p.name },
  });
}

// Edge cases: Nomen should ask rather than guess, or must not fall into a known trap.
const edge = (id, tag, expect, input) => cases.push({ id: `edge-${id}`, tags: ["edge", tag], expect, prompt: `${input.freeText} · ${input.productType}`, input, meta: {} });
edge("nice-dress", "should-ask", "ask", { freeText: "nice dress", productType: "dress" });
edge("cute-top", "should-ask", "ask", { freeText: "cute top", productType: "top" });
edge("mini-and-maxi", "should-ask", "ask", { freeText: "black mini dress, maxi length", productType: "dress" });
edge("strapless-and-strappy", "should-ask", "ask", { freeText: "strapless strappy maxi dress", productType: "dress" });
edge("strappy-trap", "trap", "name", { freeText: "white strappy satin slip dress, maxi", productType: "dress" });
edge("mesh-sleeves-trap", "trap", "name", { freeText: "black dress with ruching, midi length, mesh sleeves", productType: "dress" });

writeFileSync(new URL("./cases.json", import.meta.url), JSON.stringify(cases, null, 1) + "\n");

// Review file: a table, then every case's exact input.
const fence = "````";
const md = [`# Nomen test cases (${cases.length})`, "", "Generated by build-cases.mjs from Sportsgirl's public product pages. Expected: **name** = Nomen should write a name; **ask** = Nomen should ask for more detail instead.", "",
  "| id | group | expected | what the buyer typed | type | colour / print |", "|---|---|---|---|---|---|",
  ...cases.map((c) => `| ${c.id} | ${c.tags[0]} | ${c.expect} | ${c.input.freeText} | ${c.input.productType} | ${c.input.colour ?? c.input.pattern ?? ""} |`), "",
  ...cases.flatMap((c) => [`## ${c.id}`, c.meta.sportsgirl_name ? `Sportsgirl's current name: ${c.meta.sportsgirl_name} (${c.meta.url})` : "", fence, JSON.stringify(c.input, null, 2), fence, ""])];
writeFileSync(new URL("./cases.md", import.meta.url), md.join("\n"));
console.log(`${cases.length} cases (${cases.filter((c) => c.tags[0] !== "edge").length} catalogue, ${cases.filter((c) => c.tags[0] === "edge").length} edge)`);
